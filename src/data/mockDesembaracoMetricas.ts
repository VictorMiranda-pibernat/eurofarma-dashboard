
import {
  calendarioPadrao,
  calendarioCorridos,
  type ConfiguracaoMetrica,
  type ConfiguracaoSla,
  type Modal,
  type CalendarioOperacional,
  type UnidadePrazo,
} from '../types/metricas'

const criarFaixas = (verde: number, sla: number) => ({
  verdeAteHoras: verde,
  atencaoAteHoras: sla,
  alertaAteHoras: sla,
})

function criarSla(
  aereo: [number, number],
  maritimo: [number, number],
  rodoviario: [number, number],
): ConfiguracaoSla {
  return {
    Aéreo: criarFaixas(...aereo),
    Marítimo: criarFaixas(...maritimo),
    Rodoviário: criarFaixas(...rodoviario),
  }
}

function criarCalendarios(
  aereo: CalendarioOperacional = calendarioPadrao,
  maritimo: CalendarioOperacional = calendarioPadrao,
  rodoviario: CalendarioOperacional = calendarioPadrao,
): Record<Modal, CalendarioOperacional> {
  return {
    Aéreo: aereo,
    Marítimo: maritimo,
    Rodoviário: rodoviario,
  }
}

function criarUnidades(
  aereo: UnidadePrazo = 'dias úteis',
  maritimo: UnidadePrazo = 'dias úteis',
  rodoviario: UnidadePrazo = 'dias úteis',
): Record<Modal, UnidadePrazo> {
  return {
    Aéreo: aereo,
    Marítimo: maritimo,
    Rodoviário: rodoviario,
  }
}

